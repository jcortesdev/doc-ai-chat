import { BenchmarkReportView } from '@/components/benchmark-report';
import { PageHelp } from '@/components/page-help';
import { getBenchmarkReport } from '@/lib/benchmark';
import { getTranslations, setRequestLocale } from 'next-intl/server';

type Props = {
  params: Promise<{ locale: string }>;
};

// Public report page (M7, ADR-021): the same committed golden-set-vs-6-combos
// result for every visitor — no sign-in, no per-user data (middleware.ts
// public routes). Unlike /account's BYOK selector, this page never triggers a
// paid model call itself; it only reads packages/evals/benchmark-results/
// latest.json, regenerated by hand via `pnpm bench:run` and committed.
export default async function BenchmarkPage({ params }: Props) {
  const { locale } = await params;
  setRequestLocale(locale);
  const t = await getTranslations('benchmark');
  const report = getBenchmarkReport();

  return (
    <main className="mx-auto flex w-full max-w-2xl flex-1 flex-col gap-8 px-6 py-10 xl:max-w-5xl">
      <div className="flex flex-col gap-1">
        <div className="flex items-center gap-2">
          <h1 className="font-bold text-2xl tracking-tight">{t('title')}</h1>
          <PageHelp body={t('help')} />
        </div>
        <p className="text-foreground/70 text-sm">{t('hint')}</p>
      </div>

      {report ? (
        <BenchmarkReportView report={report} />
      ) : (
        <p className="text-foreground/70 text-sm">{t('empty')}</p>
      )}
    </main>
  );
}
